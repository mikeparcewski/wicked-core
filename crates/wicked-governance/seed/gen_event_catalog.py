RUST_CONST = re.compile(
    r'^pub const ([A-Z_][A-Z0-9_]*): &str = "(wicked\.[a-z0-9_.-]+)";', re.M
)
TS_CONST = re.compile(
    r"^export const ([A-Z_][A-Z0-9_]*) = '(wicked\.[a-z0-9_.-]+)';", re.M
)
EMIT_OPENER = re.compile(r"EmitEvent::new\(|BusEmit::new\(|\.emit\(")


def die(msg: str) -> None:
    print(f"gen_event_catalog: error: {msg}", file=sys.stderr)
    sys.exit(1)


def read(ws: Path, repo: str, rel: str) -> str:
    p = ws / repo / rel
    if not p.is_file():
        die(f"seam missing: {p} — run with --workspace pointing at the directory "
            f"that contains the wicked-* checkouts")
    return p.read_text(encoding="utf-8")


# ---------------------------------------------------------------------------
# Parsers — each returns [(event_type, extra)] where extra is a dict
# ---------------------------------------------------------------------------

def parse_rust_consts(text: str):
    out = []
    for m in RUST_CONST.finditer(text):
        line = text.count("\n", 0, m.start()) + 1
        out.append((m.group(2), {"const": m.group(1), "line": line}))
    return out


def parse_ts_consts(text: str):
    out = []
    for m in TS_CONST.finditer(text):
        line = text.count("\n", 0, m.start()) + 1
        out.append((m.group(2), {"const": m.group(1), "line": line}))
    return out


def parse_literals(text: str):
    return [(m.group(1), {}) for m in EVENT_LITERAL.finditer(text)]


def block(text: str, start_re: str, end_re: str, label: str) -> str:
    m = re.search(start_re, text, re.M)
    if not m:
        die(f"cannot find start of {label}")
    e = re.search(end_re, text[m.end():], re.M)
    if not e:
        die(f"cannot find end of {label}")
    return text[m.end(): m.end() + e.start()]


def parse_python_map(text: str):
    """BUS_EVENT_MAP in wicked-garden scripts/_bus.py."""
    body = block(text, r"^BUS_EVENT_MAP: Dict\[str, Dict\[str, str\]\] = \{", r"^\}", "BUS_EVENT_MAP")
    out = []
    entry_re = re.compile(
        r'^    "(wicked\.[a-z0-9_.-]+)": \{\n(.*?)^    \},', re.M | re.S
    )
    for m in entry_re.finditer(body):
        ev, entry = m.group(1), m.group(2)
        desc = re.search(r'"description":\s*"((?:[^"\\]|\\.)*)"', entry)
        dom = re.search(r'"domain":\s*"((?:[^"\\]|\\.)*)"', entry)
        out.append((ev, {
            "description": desc.group(1) if desc else "",
            "domain_stamp": dom.group(1) if dom else "",
        }))
    if not out:
        die("BUS_EVENT_MAP parsed to zero entries — format changed?")
    return out


def parse_js_registry(text: str):
    """EVENT_TYPES in wicked-interactive src/service/events.js."""
    body = block(text, r"^export const EVENT_TYPES = Object\.freeze\(\{", r"^\}\);", "EVENT_TYPES")
    out = []
    entry_re = re.compile(
        r'"(wicked\.[a-z0-9_.-]+)":\s*\{\s*subdomain:\s*"([a-z0-9_]+)",\s*'
        r"owners:\s*\[([A-Z_,\s]+)\],\s*uiEmittable:\s*(true|false)"
    )
    for m in entry_re.finditer(body):
        owners = ", ".join(o.strip().lower() for o in m.group(3).split(","))
        out.append((m.group(1), {
            "description": f"subdomain `{m.group(2)}`; owners: {owners}"
                           + ("; UI-emittable" if m.group(4) == "true" else ""),
        }))
    if not out:
        die("EVENT_TYPES parsed to zero entries — format changed?")
    return out


PARSERS = {
    "rust_consts": parse_rust_consts,
    "ts_consts": parse_ts_consts,
    "literals": parse_literals,
    "python_map": parse_python_map,
    "js_registry": parse_js_registry,
}


def parse_event_catalog_members(text: str) -> list[str]:
    body = block(text, r"^pub const EVENT_CATALOG: &\[&str\] = &\[", r"^\];", "EVENT_CATALOG")
    members = re.findall(r"\b(EV_[A-Z0-9_]+)\b", body)
    if not members:
        die("EVENT_CATALOG parsed to zero members — format changed?")
    return members


# ---------------------------------------------------------------------------
# Core emit-wiring scan (the declared-vs-emitted query)
# ---------------------------------------------------------------------------

def strip_test_tail(text: str) -> str:
    """Drop everything from the first top-level `#[cfg(test)]` to EOF
    (convention in this codebase: the test module is the file's tail)."""
    m = re.search(r"^#\[cfg\(test\)\]", text, re.M)
    return text[: m.start()] if m else text


def scan_core_emit_wiring(ws: Path, consts: dict[str, dict]) -> dict[str, list[str]]:
    """const name -> sorted list of repo-relative files where the const (or its
    literal type) sits within 3 lines of an emit-call opener, outside tests."""
    core = ws / "wicked-core"
    wired: dict[str, set[str]] = {name: set() for name in consts}
    rs_files = sorted(
        p for p in list((core / "src").rglob("*.rs")) + list((core / "crates").rglob("*.rs"))
        if "/tests/" not in p.as_posix() and "/target/" not in p.as_posix()
    )
    for p in rs_files:
        lines = strip_test_tail(p.read_text(encoding="utf-8")).splitlines()
        rel = p.relative_to(core).as_posix()
        opener_ix = [i for i, ln in enumerate(lines) if EMIT_OPENER.search(ln)]
        if not opener_ix:
            continue
        for name, info in consts.items():
            pat = re.compile(rf"\b{name}\b|\"{re.escape(info['type'])}\"")
            for i in opener_ix:
                for j in range(i, min(i + 4, len(lines))):
                    if pat.search(lines[j]):
                        # a const's own declaration line is not an emit seam
                        if rel == info["decl_file"] and j + 1 == info["line"]:
                            continue
                        wired[name].add(rel)
                        break
    return {k: sorted(v) for k, v in wired.items()}


