#!/usr/bin/env python3
"""AW-21 generated views — the event catalog regenerated from machine-readable seams.

The ecosystem's event catalog used to exist in three uncross-checked hand forms
(bus SPEC.md rows, garden's generated table, the apps-core Rust catalog). This
script makes the declared seams the single authority and REGENERATES the
markdown views from them (arch-R19, descoped to TABLES ONLY):

  1. wicked-core/EVENTS.md                — whole file, fully generated
  2. wicked-bus/reqs/SPEC.md              — ONLY the tables between the
     `BEGIN/END GENERATED EVENT-CATALOG TABLES (AW-21)` markers; every other
     line of SPEC.md is hand-authored and never touched

Declared-vs-emitted drift is computed, not guessed: `--drift` prints the same
report the EVENTS.md drift section embeds (add `--json` for machines).

Seams scanned (all machine-readable; see SEAMS below):
  wicked-core     Rust `pub const X: &str = "wicked...";` declarations + the
                  apps-core `EVENT_CATALOG` array + emit-call windows
                  (`EmitEvent::new(` / `BusEmit::new(` / `.emit(`, non-test)
  wicked-garden   `scripts/_bus.py` BUS_EVENT_MAP (registry) and
                  `scripts/qe/lib/gate.mjs` literals (emit)
  wicked-ledger   `lib/bus-emit.mjs` literals (emit)
  wicked-crew     `packages/crew/src/projects/events.ts` consts (producer) and
                  `packages/crew/src/interactive/*-events.ts` consts (consumer
                  mirrors of wicked-interactive's registry)
  wicked-interactive  `src/service/events.js` EVENT_TYPES (registry) and
                  `src/artifact/{create,publish,validate}.js` literals (emit)

Trigger/payload prose that no seam carries lives in
`event-catalog-annotations.json` next to this script — curated DATA merged into
the generated rows (unknown keys are a hard error so annotations cannot rot).

Modes:
  (default)   regenerate both outputs in place
  --check     regenerate in memory, diff against disk; exit 2 when stale (CI seam)
  --drift     print the declared-vs-emitted / grammar / registry-gap report; exit 0
  --json      with --drift: emit the report as JSON

Python 3 stdlib only; forward-slash paths everywhere (cross-platform mandate).
"""

