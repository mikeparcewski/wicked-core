def grammar_violations(events: dict) -> list[dict]:
    out = []
    for t in sorted(events):
        segs = t.split(".")
        problems = []
        if len(segs) != 4:
            problems.append(f"{len(segs)} segments (grammar requires exactly 4)")
        bad = [s for s in segs[1:] if not WB001_SEGMENT.match(s)]
        if bad:
            problems.append("segment(s) outside WB-001 charset [a-z0-9_]: "
                            + ", ".join(f"`{s}`" for s in bad))
        if len(segs) >= 2 and segs[1] not in WHITELISTED_DOMAINS | LEGACY_DOMAINS:
            problems.append(
                f"producer domain `{segs[1]}` not in the POL-1802 whitelist "
                f"({', '.join(sorted(WHITELISTED_DOMAINS))}; legacy: "
                f"{', '.join(sorted(LEGACY_DOMAINS))})")
        if problems:
            out.append({"event": t, "problems": problems})
    return out


def build_drift(events, core_consts, catalog_members, wiring):
    declared_not_wired = [
        {"const": name, "event": core_consts[name]["type"]}
        for name in catalog_members if not wiring.get(name)
    ]
    wired_outside_catalog = [
        {"const": name, "event": info["type"], "emit_files": wiring[name]}
        for name, info in sorted(core_consts.items())
        if wiring.get(name) and name not in catalog_members
    ]
    emit_only = []
    for t in sorted(events):
        roles = {r for (_, _, r) in events[t]["sources"]}
        if roles == {"emit"}:
            emit_only.append({
                "event": t,
                "emit_files": sorted(f"{repo}:{rel}" for (repo, rel, _) in events[t]["sources"]),
            })
    multi_repo = []
    for t in sorted(events):
        repos = sorted({repo for (repo, _, _) in events[t]["sources"]})
        if len(repos) > 1:
            multi_repo.append({"event": t, "repos": repos})
    return {
        "core_declared_in_EVENT_CATALOG_but_no_emit_seam": declared_not_wired,
        "core_emit_wired_but_outside_EVENT_CATALOG": wired_outside_catalog,
        "emit_seam_only_no_registry_or_const_declaration": emit_only,
        "grammar_violations": grammar_violations(events),
        "declared_in_multiple_repos": multi_repo,
    }


def drift_text(drift: dict) -> str:
    L = []
    L.append("## Declared-vs-emitted drift (computed from the seams — a query, not a guess)")
    L.append("")
    L.append("### Declared in apps-core `EVENT_CATALOG` but no emit seam found (non-test)")
    L.append("")
    rows = drift["core_declared_in_EVENT_CATALOG_but_no_emit_seam"]
    if rows:
        for r in rows:
            L.append(f"- `{r['event']}` (`{r['const']}`)")
    else:
        L.append("- none")
    L.append("")
    L.append("### Emit-wired core constants declared OUTSIDE apps-core `EVENT_CATALOG`")
    L.append("")
    rows = drift["core_emit_wired_but_outside_EVENT_CATALOG"]
    if rows:
        for r in rows:
            L.append(f"- `{r['event']}` (`{r['const']}`) — emitted at "
                     + ", ".join(f"`{f}`" for f in r["emit_files"]))
    else:
        L.append("- none")
    L.append("")
    L.append("### Emit-seam-only types (no registry or const declaration anywhere)")
    L.append("")
    rows = drift["emit_seam_only_no_registry_or_const_declaration"]
    if rows:
        for r in rows:
            L.append(f"- `{r['event']}` — emitted at "
                     + ", ".join(f"`{f}`" for f in r["emit_files"]))
    else:
        L.append("- none")
    L.append("")
    L.append("### Grammar conformance (seed corpus `event-grammar.md`, POL-1801/POL-1802)")
    L.append("")
    rows = drift["grammar_violations"]
    if rows:
        for r in rows:
            L.append(f"- `{r['event']}` — " + "; ".join(r["problems"]))
    else:
        L.append("- none")
    L.append("")
    L.append("### Types with seams in more than one repo (shared contract — informational)")
    L.append("")
    rows = drift["declared_in_multiple_repos"]
    if rows:
        for r in rows:
            L.append(f"- `{r['event']}` — " + ", ".join(r["repos"]))
    else:
        L.append("- none")
    return "\n".join(L)


