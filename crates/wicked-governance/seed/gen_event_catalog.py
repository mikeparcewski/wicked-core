# Model assembly
# ---------------------------------------------------------------------------

def assemble(ws: Path):
    events: dict[str, dict] = {}
    core_consts: dict[str, dict] = {}

    def ev(t: str) -> dict:
        return events.setdefault(t, {"sources": [], "descriptions": []})

    for repo, rel, role, parser in SEAMS:
        text = read(ws, repo, rel)
        for etype, extra in PARSERS[parser](text):
            e = ev(etype)
            src = (repo, rel, role)
            if src not in e["sources"]:
                e["sources"].append(src)
            if extra.get("description"):
                e["descriptions"].append((repo, extra["description"]))
            if repo == "wicked-core" and "const" in extra:
                core_consts[extra["const"]] = {
                    "type": etype, "decl_file": rel, "line": extra["line"],
                }

    catalog_members = parse_event_catalog_members(
        read(ws, "wicked-core", "crates/wicked-apps-core/src/lib.rs"))
    unknown = [m for m in catalog_members if m not in core_consts]
    if unknown:
        die(f"EVENT_CATALOG members not found as consts: {unknown}")

    wiring = scan_core_emit_wiring(ws, core_consts)

    if ANNOTATIONS.is_file():
        ann = json.loads(ANNOTATIONS.read_text(encoding="utf-8"))
        ann.pop("_comment", None)
    else:
        ann = {}
    stale = sorted(set(ann) - set(events))
    if stale:
        die(f"annotations for unknown event types (edit {ANNOTATIONS.name}): {stale}")

    return events, core_consts, catalog_members, wiring, ann


