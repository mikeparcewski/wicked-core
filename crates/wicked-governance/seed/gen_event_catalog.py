def src_cell(t: str, sources, core_wired_types: set) -> str:
    parts = []
    for repo, rel, role in sorted(sources):
        tag = role
        if repo == "wicked-core" and role == "const" and t not in core_wired_types:
            tag = "const — **no emit seam**"
        parts.append(f"`{REPO_ALIAS[repo]}:{rel}` ({tag})")
    return "<br>".join(parts)


def notes_for(t: str, events: dict, ann: dict) -> tuple[str, str]:
    a = ann.get(t, {})
    trigger = a.get("trigger", "")
    payload = a.get("payload", "")
    if not trigger:
        descs = events[t]["descriptions"]
        if descs:
            # prefer the owning registry's description; they are already
            # per-repo curated strings
            trigger = descs[0][1]
    return (trigger or "—", payload or "—")


def render_domain_tables(events: dict, ann: dict, core_wired_types: set) -> str:
    by_domain: dict[str, list[str]] = {}
    for t in events:
        by_domain.setdefault(t.split(".")[1], []).append(t)
    L = []
    for dom in sorted(by_domain):
        note = DOMAIN_NOTES.get(dom, "")
        L.append(f"#### `{dom}` events" + (f" — {note}" if note else ""))
        L.append("")
        L.append("| Event type | Declared / emitted at | Trigger / description | Key payload fields |")
        L.append("|---|---|---|---|")
        for t in sorted(by_domain[dom]):
            trigger, payload = notes_for(t, events, ann)
            L.append(f"| `{t}` | {src_cell(t, events[t]['sources'], core_wired_types)} | {trigger} | {payload} |")
        L.append("")
    return "\n".join(L).rstrip("\n")


def core_wired_types(core_consts: dict, wiring: dict) -> set:
    return {info["type"] for name, info in core_consts.items() if wiring.get(name)}


def render_spec_block(events: dict, ann: dict, wired: set) -> str:
    return MARKER_BEGIN + "\n\n" + render_domain_tables(events, ann, wired) + "\n\n" + MARKER_END


def render_events_md(events, core_consts, catalog_members, wiring, ann) -> str:
    L = []
    L.append("# wicked-core event catalog (generated)")
    L.append("")
    L.append("> **GENERATED FILE — do not hand-edit.** Regenerate with")
    L.append("> `python3 crates/wicked-governance/seed/gen_event_catalog.py --workspace <dir containing the wicked-* checkouts>`.")
    L.append("> Rows come from the machine-readable seams listed under \"Seams scanned\";")
    L.append("> trigger/payload prose comes from `crates/wicked-governance/seed/event-catalog-annotations.json`.")
    L.append("> `--check` exits non-zero when this file or the wicked-bus SPEC catalog block is stale;")
    L.append("> `--drift [--json]` prints the drift report below as a standalone query.")
    L.append("")
    L.append("## Core-declared event constants")
    L.append("")
    L.append("| Constant | Event type | Declared at | In apps-core `EVENT_CATALOG` | Emit seam (non-test) |")
    L.append("|---|---|---|---|---|")
    for name in sorted(core_consts):
        info = core_consts[name]
        in_cat = "yes" if name in catalog_members else "no"
        files = wiring.get(name) or []
        emit = ", ".join(f"`{f}`" for f in files) if files else "—"
        L.append(f"| `{name}` | `{info['type']}` | `{info['decl_file']}:{info['line']}` | {in_cat} | {emit} |")
    L.append("")
    L.append("An emit seam is a non-test line referencing the constant (or its literal type)")
    L.append("within 3 lines of `EmitEvent::new(` / `BusEmit::new(` / `.emit(` — the same")
    L.append("window `--drift` queries. \"—\" means no emit seam found in the scanned")
    L.append("wicked-core sources: declared, not emit-wired HERE (an emitter in another repo,")
    L.append("e.g. the requester side of `wicked.crew.run.requested`, is outside this scan).")
    L.append("")
    drift = build_drift(events, core_consts, catalog_members, wiring)
    L.append(drift_text(drift))
    L.append("")
    L.append("## Ecosystem catalog (all domains)")
    L.append("")
    L.append("The same generated tables are published into `wicked-bus/reqs/SPEC.md` §Event")
    L.append("Catalog (between the AW-21 markers) — the bus SPEC remains the reader-facing")
    L.append("home of the catalog; this file is the engine-side view plus the drift report.")
    L.append("")
    L.append(render_domain_tables(events, ann, core_wired_types(core_consts, wiring)))
    L.append("")
    L.append("## Seams scanned")
    L.append("")
    L.append("| Repo | File | Role |")
    L.append("|---|---|---|")
    for repo, rel, role, _parser in SEAMS:
        L.append(f"| {repo} | `{rel}` | {role} |")
    L.append("")
    return "\n".join(L)


def splice_spec(spec_text: str, block_text: str) -> str:
    begin = spec_text.find(MARKER_BEGIN)
    end = spec_text.find(MARKER_END)
    if begin == -1 or end == -1:
        die("wicked-bus/reqs/SPEC.md is missing the AW-21 generated-catalog markers "
            f"({MARKER_BEGIN[:60]}…). Place both markers inside §Event Catalog first.")
    return spec_text[:begin] + block_text + spec_text[end + len(MARKER_END):]


