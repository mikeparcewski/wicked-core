#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum TargetKind {
    Lib,
    Bin,
    Test,
    Other,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct Target {
    pub kind: TargetKind,
    pub name: String,
    /// Repo-relative.
    pub src: String,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct Package {
    pub name: String,
    /// Repo-relative manifest directory (`""` for the root).
    pub dir: String,
    pub targets: Vec<Target>,
    /// Workspace members this package depends on by path (any dependency kind).
    pub member_deps: Vec<String>,
}

#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub(crate) struct Workspace {
    pub packages: Vec<Package>,
    /// Repo-relative directories of path dependencies that are NOT workspace members: a change
    /// there reaches a member's build, so it runs the full suite.
    pub outside_path_deps: Vec<String>,
}

#[derive(Deserialize)]
struct Meta {
    packages: Vec<MetaPackage>,
    workspace_members: Vec<String>,
    workspace_root: String,
}

#[derive(Deserialize)]
struct MetaPackage {
    id: String,
    name: String,
    manifest_path: String,
    targets: Vec<MetaTarget>,
    #[serde(default)]
    dependencies: Vec<MetaDep>,
}

#[derive(Deserialize)]
struct MetaTarget {
    kind: Vec<String>,
    name: String,
    src_path: String,
}

#[derive(Deserialize)]
struct MetaDep {
    #[serde(default)]
    path: Option<String>,
}

fn relative(path: &str, root: &str) -> Option<String> {
    let root = root.trim_end_matches('/');
    if path == root {
        return Some(String::new());
    }
    path.strip_prefix(&format!("{root}/")).map(str::to_string)
}

fn dir_of(path: &str) -> &str {
    path.rsplit_once('/').map(|(d, _)| d).unwrap_or("")
}

fn base_name(path: &str) -> &str {
    path.rsplit_once('/').map(|(_, b)| b).unwrap_or(path)
}

/// Parse `cargo metadata --format-version 1 --no-deps` output.
pub(crate) fn parse_metadata(json: &str) -> Result<Workspace, String> {
    let m: Meta =
        serde_json::from_str(json).map_err(|e| format!("cargo metadata did not parse ({e})"))?;
    let root = m.workspace_root.clone();
    let members: HashSet<&str> = m.workspace_members.iter().map(String::as_str).collect();
    let mut packages = Vec::new();
    let mut dep_dirs: Vec<(String, Vec<String>)> = Vec::new();
    for p in m
        .packages
        .iter()
        .filter(|p| members.contains(p.id.as_str()))
    {
        let dir = relative(dir_of(&p.manifest_path), &root)
            .ok_or_else(|| format!("`{}` is outside the workspace root", p.manifest_path))?;
        let mut targets = Vec::new();
        for t in &p.targets {
            let kind = if t
                .kind
                .iter()
                .any(|k| k.ends_with("lib") || k == "proc-macro")
            {
                TargetKind::Lib
            } else if t.kind.iter().any(|k| k == "bin") {
                TargetKind::Bin
            } else if t.kind.iter().any(|k| k == "test") {
                TargetKind::Test
            } else {
                TargetKind::Other
            };
            let src = relative(&t.src_path, &root)
                .ok_or_else(|| format!("`{}` is outside the workspace root", t.src_path))?;
            targets.push(Target {
                kind,
                name: t.name.clone(),
                src,
            });
        }
        let deps = p
            .dependencies
            .iter()
            .filter_map(|d| d.path.as_deref().and_then(|x| relative(x, &root)))
            .collect();
        dep_dirs.push((p.name.clone(), deps));
        packages.push(Package {
            name: p.name.clone(),
            dir,
            targets,
            member_deps: Vec::new(),
        });
    }
    let by_dir: HashMap<String, String> = packages
        .iter()
        .map(|p| (p.dir.clone(), p.name.clone()))
        .collect();
    let mut outside = BTreeSet::new();
    for (name, deps) in dep_dirs {
        let mut member_deps = Vec::new();
        for d in deps {
            match by_dir.get(&d) {
                Some(n) => member_deps.push(n.clone()),
                None => {
                    outside.insert(d);
                }
            }
        }
        if let Some(p) = packages.iter_mut().find(|p| p.name == name) {
            p.member_deps = member_deps;
        }
    }
    Ok(Workspace {
        packages,
        outside_path_deps: outside.into_iter().collect(),
    })
}

impl Workspace {
    fn package(&self, name: &str) -> Option<&Package> {
        self.packages.iter().find(|p| p.name == name)
    }

    /// Every member that depends on one of `names`, transitively, with `names` themselves.
    fn reverse_closure(&self, names: &BTreeSet<String>) -> BTreeSet<String> {
        let mut out = names.clone();
        loop {
            let before = out.len();
            for p in &self.packages {
                if p.member_deps.iter().any(|d| out.contains(d)) {
                    out.insert(p.name.clone());
                }
            }
            if out.len() == before {
                return out;
            }
        }
    }
}

// ── what a file is ───────────────────────────────────────────────────────────────────────────

#[derive(Debug, Clone, PartialEq, Eq)]
enum Place {
    /// A member's lib source.
    Lib(String),
    /// A member's binary (package, bin name).
    Bin(String, String),
    /// One integration target's root file (package, target).
    TestRoot(String, String),
    /// A file under a member's `tests/` that is no target's root (a shared module or fixture).
    TestModule(String),
    /// Inside a package that is not a workspace member: no workspace test can reach it.
    Outside,
    /// A member's file the targets do not explain.
    Unmapped(String),
}

/// Where `file` sits. `manifest_dirs` are the repo-relative directories holding a `Cargo.toml`
/// in the head tree (a member's or an excluded package's).
fn place(ws: &Workspace, manifest_dirs: &BTreeSet<String>, file: &str) -> Place {
    let mut d = dir_of(file);
    let owner = loop {
        if manifest_dirs.contains(d) {
            break Some(d);
        }
        if d.is_empty() {
            break None;
        }
        d = dir_of(d);
    };
    let Some(owner) = owner else {
        return Place::Unmapped(String::new());
    };
    let Some(pkg) = ws.packages.iter().find(|p| p.dir == owner) else {
        // (xreview) A virtual workspace root is no package, yet not outside the workspace.
        return if owner.is_empty() {
            Place::Unmapped(String::new())
        } else {
            Place::Outside
        };
    };
    for t in &pkg.targets {
        if t.src == file {
            return match t.kind {
                TargetKind::Lib => Place::Lib(pkg.name.clone()),
                TargetKind::Bin => Place::Bin(pkg.name.clone(), t.name.clone()),
                TargetKind::Test => Place::TestRoot(pkg.name.clone(), t.name.clone()),
                TargetKind::Other => Place::Unmapped(pkg.name.clone()),
            };
        }
    }
    let prefix = |p: &str| {
        if owner.is_empty() {
            p.to_string()
        } else {
            format!("{owner}/{p}")
        }
    };
    // A binary's own directory: `…/<name>/` for `src/bin/<name>.rs`, the root's directory for
    // `src/bin/<name>/main.rs` (xreview: never the whole `src/bin/`).
    let src_dir = prefix("src");
    for t in pkg.targets.iter().filter(|t| t.kind == TargetKind::Bin) {
        let own = if base_name(&t.src) == "main.rs" {
            dir_of(&t.src).to_string()
        } else {
            format!(
                "{}/{}",
                dir_of(&t.src),
                base_name(&t.src).trim_end_matches(".rs")
            )
        };
        if own != src_dir && file.starts_with(&format!("{own}/")) {
            return Place::Bin(pkg.name.clone(), t.name.clone());
        }
    }
    let bins = prefix("src/bin/");
    if let Some(lib) = pkg.targets.iter().find(|t| t.kind == TargetKind::Lib) {
        let dir = dir_of(&lib.src);
        if file.starts_with(&format!("{dir}/")) && !file.starts_with(&bins) {
            return Place::Lib(pkg.name.clone());
        }
    } else if let Some(main) = pkg
        .targets
        .iter()
        .find(|t| t.kind == TargetKind::Bin && t.src == prefix("src/main.rs"))
    {
        // (xreview) A package with no lib: its `src/` modules are its binary's.
        if file.starts_with(&format!("{src_dir}/")) && !file.starts_with(&bins) {
            return Place::Bin(pkg.name.clone(), main.name.clone());
        }
    }
    if file.starts_with(&prefix("tests/")) {
        return Place::TestModule(pkg.name.clone());
    }
    Place::Unmapped(pkg.name.clone())
}

fn shared_infra(file: &str) -> bool {
    let name = base_name(file);
    name == "Cargo.toml"
        || name == "Cargo.lock"
        || name == "build.rs"
        || name.starts_with("rust-toolchain")
        || file.starts_with(".cargo/")
        || file.contains("/.cargo/")
}

