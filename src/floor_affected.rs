//! FLOOR AFFECTED SET (core#1187) — the creator floor's test selection for a cargo workspace,
//! computed by the ENGINE from the run's diff. Never chosen by the creator's seat or the intake
//! model (evaluator≠creator): the plan's check list can only ADD checks, it never narrows this.
//!
//! A repo-checks `test` check that is `cargo test … --workspace` runs, at the CREATOR floor, this
//! subset first; its pass decides, its failure runs the check as declared (the same contract as a
//! build guide's `affected` piece, which wins when the base's guide has a usable one). The verify
//! floor always runs the declared suite, and a power run at high rigor or above runs the full suite
//! at hand-off too ([`crate::power::full_suite_required`]).
//!
//! # How the set is computed
//!
//! 1. **Cargo's package graph** (`cargo metadata --no-deps`): the workspace members, their test
//!    targets, and which member depends on which by path. A touched file belongs to the member
//!    whose manifest is nearest above it; a package outside the workspace (an `exclude`d crate)
//!    is not part of `cargo test --workspace`, so its files reach no test here.
//! 2. **Estate's code graph**, indexed at the run BASE (the launch re-indexes a stale graph,
//!    `code_graph::index_at_base`): the symbols whose base-side lines the diff touches are the
//!    seeds, and their blast radius is every dependent the graph knows: resolved edges (not
//!    containment), plus the call sites estate could not resolve to one definition
//!    (`unresolved_refs_for_name` — Rust calls are matched by name, and an ambiguous name keeps
//!    its sites unresolved), plus, for a non-function symbol (a constant, a type), the lines that
//!    name it. A name with more than [`FAN_IN`] candidate sites (`new`, `run`, `expect`) is
//!    matched by name alone too often to mean anything, so its sites count only in the defining
//!    file or in a file that names the defining type or module. A reach past [`MAX_REACH`]
//!    symbols runs every affected package whole.
//! 3. **The tests**: every test function the radius reaches, every test in a touched file, every
//!    test that names a touched file (a source scan, an `include_str!` fixture), every integration
//!    target holding one of them, and a binary's integration tests (`CARGO_BIN_EXE_<bin>`) when
//!    the radius reaches that binary. Lib tests run as name filters (`--lib -- <name>…`), each
//!    package in its own invocation; a touched doc example runs that package's doc tests.
//!
//! # When the full suite runs instead (said in the selection's `reason`)
//!
//! Shared infrastructure (any `Cargo.toml`, `Cargo.lock`, `build.rs`, `.cargo/`,
//! `rust-toolchain*`, a crate root `lib.rs`/`main.rs`, or a path the BASE tree's
//! [`AFFECTED_CONFIG`] lists under `full`); a deleted or renamed file; a changed line outside every
//! symbol the graph knows (a macro body); a non-Rust file no source names (Markdown excepted);
//! no graph, a graph indexed at another commit, or one that cannot be read; a workspace cargo
//! cannot describe; a selection that names no test at all (the engine never passes a check by
//! running nothing).
//!
//! # What it cannot see
//!
//! A function passed as a value (`map(f)`), a test generated by a macro, behaviour reached across a
//! process boundary other than a workspace binary. The verify floor's full suite is the backstop.

use std::collections::{BTreeMap, BTreeSet, HashMap, HashSet};
use std::path::Path;

use serde::{Deserialize, Serialize};
use wicked_apps_core::{GraphRead, NodeKind};
use wicked_estate_core::{Direction, EdgeKind};

/// The base tree's optional widening list: `{"full": ["src/actor.rs", "src/actor/**"]}`. Read
/// from the BASE commit only, so a change cannot narrow its own floor; it can only make the full
/// suite run.
pub const AFFECTED_CONFIG: &str = ".wicked/affected.json";
/// A blast radius past this many symbols runs every affected package whole.
pub(crate) const MAX_REACH: usize = 3000;
/// A name with more candidate sites than this is matched only where the defining type or module
/// is named (see the module docs).
pub(crate) const FAN_IN: usize = 20;
/// Lib test names past this many run the package's lib tests whole.
const MAX_FILTERS: usize = 2000;
/// How many selected test names the record carries (the count is always whole).
const RECORDED_TESTS: usize = 100;

pub const MODE_AFFECTED: &str = "affected";
pub const MODE_FULL: &str = "full";

/// What the engine selected for a cargo workspace `test` check at the creator floor, and why.
/// Rides the check on `repoChecksEvaluated` (`checks[].selection`).
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct TestSelection {
    /// [`MODE_AFFECTED`] (the subset below ran first) or [`MODE_FULL`] (the check as declared).
    pub mode: String,
    /// Why: how the subset was reached, or what made the full suite run.
    pub reason: String,
    /// The packages whose tests the subset runs.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub packages: Vec<String>,
    /// One line per invocation: `wicked-core --lib (12 tests)`, `wicked-core --test foo`.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub targets: Vec<String>,
    /// The lib tests selected by name (the first [`RECORDED_TESTS`]; `test_count` is whole).
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub tests: Vec<String>,
    #[serde(default)]
    pub test_count: u32,
    /// Symbols the diff touches (the seeds) and symbols their blast radius reached.
    #[serde(default)]
    pub changed_symbols: u32,
    #[serde(default)]
    pub reached_symbols: u32,
}

impl TestSelection {
    pub(crate) fn full(reason: impl Into<String>) -> Self {
        TestSelection {
            mode: MODE_FULL.into(),
            reason: reason.into(),
            ..Default::default()
        }
    }

    /// The note the check's summary carries.
    pub fn note(&self) -> String {
        if self.mode == MODE_AFFECTED {
            format!(
                "affected set: {} invocation(s), {} named lib test(s); {}",
                self.targets.len(),
                self.test_count,
                self.reason
            )
        } else {
            format!("full suite: {}", self.reason)
        }
    }
}

/// The selection and, for [`MODE_AFFECTED`], the one argv that runs it.
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct Plan {
    pub selection: TestSelection,
    pub argv: Option<Vec<String>>,
}

impl Plan {
    pub(crate) fn full(reason: impl Into<String>) -> Self {
        Plan {
            selection: TestSelection::full(reason),
            argv: None,
        }
    }
}

/// A `cargo test … --workspace` check, split for re-composition: its options (without
/// `--workspace`/`--all`) and its test-binary arguments (after `--`).
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct CargoTest {
    pub opts: Vec<String>,
    pub test_args: Vec<String>,
}

/// `Some` when `argv` is `cargo test` over the whole workspace with only options the subset can
/// carry over unchanged; anything else (a feature flag, a package or target selector) is left
/// alone.
pub(crate) fn cargo_workspace_test(argv: &[String]) -> Option<CargoTest> {
    let (head, tail) = match argv.iter().position(|a| a == "--") {
        Some(i) => (&argv[..i], argv[i + 1..].to_vec()),
        None => (argv, Vec::new()),
    };
    if head.len() < 2 || head[0] != "cargo" || head[1] != "test" {
        return None;
    }
    let mut opts = Vec::new();
    let mut workspace = false;
    let mut it = head[2..].iter();
    while let Some(a) = it.next() {
        match a.as_str() {
            "--workspace" | "--all" => workspace = true,
            "--locked" | "--frozen" | "--offline" | "--no-fail-fast" | "-q" | "--quiet" | "-v"
            | "--verbose" => opts.push(a.clone()),
            "-j" | "--jobs" => {
                let n = it.next()?;
                if !n.chars().all(|c| c.is_ascii_digit()) {
                    return None;
                }
                opts.push(a.clone());
                opts.push(n.clone());
            }
            s if s.starts_with("--jobs=") || (s.starts_with("-j") && s.len() > 2) => {
                opts.push(a.clone())
            }
            _ => return None,
        }
    }
    // (xreview) Only test-binary options that keep a selected name a substring filter and a run
    // a run: `--exact`, `--skip`, `--ignored` or a filter of the check's own would change what
    // the subset means (`--exact adds` matches no `calc::adds` and passes on zero tests).
    let mut args = tail.iter();
    while let Some(a) = args.next() {
        match a.as_str() {
            "--nocapture" | "--show-output" | "-q" | "--quiet" | "--include-ignored" => {}
            "--test-threads" | "--color" => {
                args.next()?;
            }
            s if s.starts_with("--test-threads=") || s.starts_with("--color=") => {}
            _ => return None,
        }
    }
    workspace.then_some(CargoTest {
        opts,
        test_args: tail,
    })
}

